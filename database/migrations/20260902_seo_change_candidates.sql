CREATE TABLE IF NOT EXISTS seo_change_candidates (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  organization_id BIGINT UNSIGNED NOT NULL,
  site_id BIGINT UNSIGNED NOT NULL,
  page_id BIGINT UNSIGNED NOT NULL,
  issue_id BIGINT UNSIGNED NULL,
  candidate_type ENUM('metadata') NOT NULL DEFAULT 'metadata',
  original_title VARCHAR(500) NULL,
  original_description TEXT NULL,
  candidate_title VARCHAR(160) NOT NULL,
  candidate_description VARCHAR(500) NOT NULL,
  rationale VARCHAR(1000) NULL,
  evidence JSON NOT NULL,
  model_code VARCHAR(100) NOT NULL,
  status ENUM('draft','approved','rejected','exported') NOT NULL DEFAULT 'draft',
  created_by INT NOT NULL,
  approved_by INT NULL,
  approved_at DATETIME NULL,
  exported_at DATETIME NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  KEY idx_candidate_org_status (organization_id,status,created_at),
  KEY idx_candidate_page (page_id,created_at),
  CONSTRAINT fk_candidate_org FOREIGN KEY (organization_id) REFERENCES organizations(id) ON DELETE CASCADE,
  CONSTRAINT fk_candidate_site FOREIGN KEY (site_id) REFERENCES seo_sites(id) ON DELETE CASCADE,
  CONSTRAINT fk_candidate_page FOREIGN KEY (page_id) REFERENCES seo_pages(id) ON DELETE CASCADE,
  CONSTRAINT fk_candidate_issue FOREIGN KEY (issue_id) REFERENCES seo_issues(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

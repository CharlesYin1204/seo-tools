-- 为用户表添加profile页面需要的字段
-- 确保所有profile表单字段都有对应的数据库列

-- 检查并添加缺失的字段到users表
ALTER TABLE users 
ADD COLUMN IF NOT EXISTS city VARCHAR(100) DEFAULT NULL COMMENT '当前城市' AFTER phone,
ADD COLUMN IF NOT EXISTS district VARCHAR(100) DEFAULT NULL COMMENT '区域' AFTER city,
ADD COLUMN IF NOT EXISTS address TEXT DEFAULT NULL COMMENT '详细地址' AFTER district,
ADD COLUMN IF NOT EXISTS nationality VARCHAR(50) DEFAULT NULL COMMENT '国籍' AFTER address,
ADD COLUMN IF NOT EXISTS language VARCHAR(10) DEFAULT 'en' COMMENT '首选语言' AFTER nationality,
ADD COLUMN IF NOT EXISTS bio TEXT DEFAULT NULL COMMENT '个人简介' AFTER language,
ADD COLUMN IF NOT EXISTS budget_min INT DEFAULT NULL COMMENT '预算范围最小值' AFTER bio,
ADD COLUMN IF NOT EXISTS budget_max INT DEFAULT NULL COMMENT '预算范围最大值' AFTER budget_min,
ADD COLUMN IF NOT EXISTS preferred_areas VARCHAR(255) DEFAULT NULL COMMENT '偏好区域' AFTER budget_max,
ADD COLUMN IF NOT EXISTS avatar VARCHAR(255) DEFAULT NULL COMMENT '头像URL' AFTER preferred_areas,
ADD COLUMN IF NOT EXISTS profile_public TINYINT(1) DEFAULT 1 COMMENT '公开资料' AFTER avatar,
ADD COLUMN IF NOT EXISTS email_notifications TINYINT(1) DEFAULT 1 COMMENT '邮件通知' AFTER profile_public,
ADD COLUMN IF NOT EXISTS sms_notifications TINYINT(1) DEFAULT 0 COMMENT '短信通知' AFTER email_notifications,
ADD COLUMN IF NOT EXISTS phone_verified TINYINT(1) DEFAULT 0 COMMENT '手机验证状态' AFTER sms_notifications,
ADD COLUMN IF NOT EXISTS deactivated_at DATETIME DEFAULT NULL COMMENT '停用时间' AFTER phone_verified;

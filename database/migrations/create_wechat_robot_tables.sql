  KEY `idx_robot_id` (`robot_id`),
  KEY `idx_user_id` (`user_id`),
  KEY `idx_moment_id` (`moment_id`),
  KEY `idx_status` (`status`),
  KEY `idx_publish_at` (`publish_at`),
  KEY `idx_created_at` (`created_at`),
  CONSTRAINT `fk_moment_robot` FOREIGN KEY (`robot_id`) REFERENCES `wechat_robot_accounts` (`id`) ON DELETE CASCADE,
  CONSTRAINT `fk_moment_user` FOREIGN KEY (`user_id`) REFERENCES `users` (`id`) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='微信朋友圈表';


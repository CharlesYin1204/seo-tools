-- 自动回复规则表
CREATE TABLE IF NOT EXISTS `wechat_robot_auto_replies` (
  `id` int(11) NOT NULL AUTO_INCREMENT,
  `robot_id` int(11) NOT NULL COMMENT '机器人账号ID',
  `user_id` int(11) NOT NULL COMMENT '用户ID',
  `name` varchar(100) NOT NULL COMMENT '规则名称',
  `match_type` enum('exact','contains','regex','keyword') DEFAULT 'contains' COMMENT '匹配类型',
  `match_content` text NOT NULL COMMENT '匹配内容',
  `reply_type` enum('text','image','file','forward') DEFAULT 'text' COMMENT '回复类型',
  `reply_content` text NOT NULL COMMENT '回复内容',
  `reply_media_url` varchar(500) DEFAULT NULL COMMENT '回复媒体URL',
  `apply_to` enum('all','friend','group','specific') DEFAULT 'all' COMMENT '应用范围',
  `apply_list` json DEFAULT NULL COMMENT '指定联系人/群列表',
  `priority` int(11) DEFAULT 0 COMMENT '优先级',
  `is_active` tinyint(1) DEFAULT 1 COMMENT '是否启用',
  `trigger_count` int(11) DEFAULT 0 COMMENT '触发次数',
  `last_triggered_at` datetime DEFAULT NULL COMMENT '最后触发时间',
  `created_at` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `updated_at` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`),
  KEY `idx_robot_id` (`robot_id`),
  KEY `idx_user_id` (`user_id`),
  KEY `idx_is_active` (`is_active`),
  KEY `idx_priority` (`priority`),
  CONSTRAINT `fk_auto_reply_robot` FOREIGN KEY (`robot_id`) REFERENCES `wechat_robot_accounts` (`id`) ON DELETE CASCADE,
  CONSTRAINT `fk_auto_reply_user` FOREIGN KEY (`user_id`) REFERENCES `users` (`id`) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='自动回复规则表';


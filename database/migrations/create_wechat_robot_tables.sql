-- 微信机器人账号表 (个人微信登录)
CREATE TABLE IF NOT EXISTS `wechat_robot_accounts` (
  `id` int(11) NOT NULL AUTO_INCREMENT,
  `user_id` int(11) NOT NULL COMMENT '用户ID',
  `wxid` varchar(100) DEFAULT NULL COMMENT '微信ID',
  `nickname` varchar(100) DEFAULT NULL COMMENT '微信昵称',
  `avatar` varchar(500) DEFAULT NULL COMMENT '微信头像',
  `phone` varchar(20) DEFAULT NULL COMMENT '绑定手机号',
  `device_id` varchar(100) DEFAULT NULL COMMENT '设备ID',
  `token` varchar(500) DEFAULT NULL COMMENT 'API Token',
  `api_url` varchar(255) DEFAULT NULL COMMENT 'API基础地址',
  `status` enum('offline','online','logging','error') DEFAULT 'offline' COMMENT '在线状态',
  `login_type` varchar(50) DEFAULT 'qrcode' COMMENT '登录方式',
  `qrcode_url` varchar(500) DEFAULT NULL COMMENT '登录二维码URL',
  `qrcode_expires_at` datetime DEFAULT NULL COMMENT '二维码过期时间',
  `last_login_at` datetime DEFAULT NULL COMMENT '最后登录时间',
  `last_heartbeat_at` datetime DEFAULT NULL COMMENT '最后心跳时间',
  `last_error` text COMMENT '最后错误信息',
  `settings` json DEFAULT NULL COMMENT '机器人设置(自动回复等)',
  `is_active` tinyint(1) DEFAULT 1 COMMENT '是否启用',
  `created_at` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `updated_at` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`),
  KEY `idx_user_id` (`user_id`),
  KEY `idx_wxid` (`wxid`),
  KEY `idx_status` (`status`),
  KEY `idx_is_active` (`is_active`),
  CONSTRAINT `fk_wechat_robot_user` FOREIGN KEY (`user_id`) REFERENCES `users` (`id`) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='微信机器人账号表';

-- 微信通讯录/好友表
CREATE TABLE IF NOT EXISTS `wechat_robot_contacts` (
  `id` int(11) NOT NULL AUTO_INCREMENT,
  `robot_id` int(11) NOT NULL COMMENT '机器人账号ID',
  `user_id` int(11) NOT NULL COMMENT '用户ID',
  `wxid` varchar(100) NOT NULL COMMENT '联系人微信ID',
  `nickname` varchar(200) DEFAULT NULL COMMENT '联系人昵称',
  `remark` varchar(200) DEFAULT NULL COMMENT '备注名',
  `avatar` varchar(500) DEFAULT NULL COMMENT '头像URL',
  `sex` tinyint(1) DEFAULT 0 COMMENT '性别 0未知 1男 2女',
  `signature` text COMMENT '个性签名',
  `country` varchar(50) DEFAULT NULL COMMENT '国家',
  `province` varchar(50) DEFAULT NULL COMMENT '省份',
  `city` varchar(50) DEFAULT NULL COMMENT '城市',
  `contact_type` enum('friend','group_member','official','stranger') DEFAULT 'friend' COMMENT '联系人类型',
  `is_star` tinyint(1) DEFAULT 0 COMMENT '是否星标好友',
  `is_blocked` tinyint(1) DEFAULT 0 COMMENT '是否已屏蔽',
  `tags` json DEFAULT NULL COMMENT '标签',
  `last_message_at` datetime DEFAULT NULL COMMENT '最后消息时间',
  `created_at` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `updated_at` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`),
  UNIQUE KEY `uk_robot_wxid` (`robot_id`, `wxid`),
  KEY `idx_user_id` (`user_id`),
  KEY `idx_robot_id` (`robot_id`),
  KEY `idx_wxid` (`wxid`),
  KEY `idx_contact_type` (`contact_type`),
  CONSTRAINT `fk_contact_robot` FOREIGN KEY (`robot_id`) REFERENCES `wechat_robot_accounts` (`id`) ON DELETE CASCADE,
  CONSTRAINT `fk_contact_user` FOREIGN KEY (`user_id`) REFERENCES `users` (`id`) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='微信通讯录表';

-- 微信群组表
CREATE TABLE IF NOT EXISTS `wechat_robot_groups` (
  `id` int(11) NOT NULL AUTO_INCREMENT,
  `robot_id` int(11) NOT NULL COMMENT '机器人账号ID',
  `user_id` int(11) NOT NULL COMMENT '用户ID',
  `chatroom_id` varchar(100) NOT NULL COMMENT '群ID(群聊wxid)',
  `name` varchar(200) DEFAULT NULL COMMENT '群名称',
  `avatar` varchar(500) DEFAULT NULL COMMENT '群头像',
  `owner_wxid` varchar(100) DEFAULT NULL COMMENT '群主微信ID',
  `member_count` int(11) DEFAULT 0 COMMENT '群成员数量',
  `members` json DEFAULT NULL COMMENT '群成员列表(JSON)',
  `notice` text COMMENT '群公告',
  `is_owner` tinyint(1) DEFAULT 0 COMMENT '是否群主',
  `is_admin` tinyint(1) DEFAULT 0 COMMENT '是否管理员',
  `is_saved` tinyint(1) DEFAULT 0 COMMENT '是否保存到通讯录',
  `is_muted` tinyint(1) DEFAULT 0 COMMENT '是否消息免打扰',
  `is_topped` tinyint(1) DEFAULT 0 COMMENT '是否置顶',
  `last_message_at` datetime DEFAULT NULL COMMENT '最后消息时间',
  `created_at` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `updated_at` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`),
  UNIQUE KEY `uk_robot_chatroom` (`robot_id`, `chatroom_id`),
  KEY `idx_user_id` (`user_id`),
  KEY `idx_robot_id` (`robot_id`),
  KEY `idx_chatroom_id` (`chatroom_id`),
  CONSTRAINT `fk_group_robot` FOREIGN KEY (`robot_id`) REFERENCES `wechat_robot_accounts` (`id`) ON DELETE CASCADE,
  CONSTRAINT `fk_group_user` FOREIGN KEY (`user_id`) REFERENCES `users` (`id`) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='微信群组表';

-- 微信消息记录表
CREATE TABLE IF NOT EXISTS `wechat_robot_messages` (
  `id` bigint(20) NOT NULL AUTO_INCREMENT,
  `robot_id` int(11) NOT NULL COMMENT '机器人账号ID',
  `user_id` int(11) NOT NULL COMMENT '用户ID',
  `msg_id` varchar(100) DEFAULT NULL COMMENT '微信消息ID',
  `msg_type` int(11) NOT NULL DEFAULT 1 COMMENT '消息类型 1文本 3图片 34语音 42名片 43视频 47表情 48位置 49链接 51视频号 10000系统消息',
  `from_wxid` varchar(100) NOT NULL COMMENT '发送者wxid',
  `from_nickname` varchar(200) DEFAULT NULL COMMENT '发送者昵称',
  `to_wxid` varchar(100) NOT NULL COMMENT '接收者wxid',
  `to_nickname` varchar(200) DEFAULT NULL COMMENT '接收者昵称',
  `chatroom_id` varchar(100) DEFAULT NULL COMMENT '群聊ID(群消息时)',
  `content` text COMMENT '消息内容',
  `raw_content` longtext COMMENT '原始消息内容(XML等)',
  `media_url` varchar(500) DEFAULT NULL COMMENT '媒体文件URL',
  `thumb_url` varchar(500) DEFAULT NULL COMMENT '缩略图URL',
  `direction` enum('send','receive') DEFAULT 'receive' COMMENT '消息方向',
  `status` enum('pending','sent','delivered','read','failed') DEFAULT 'sent' COMMENT '消息状态',
  `is_at_me` tinyint(1) DEFAULT 0 COMMENT '是否@了我',
  `is_recalled` tinyint(1) DEFAULT 0 COMMENT '是否已撤回',
  `created_at` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`),
  KEY `idx_robot_id` (`robot_id`),
  KEY `idx_user_id` (`user_id`),
  KEY `idx_msg_id` (`msg_id`),
  KEY `idx_from_wxid` (`from_wxid`),
  KEY `idx_to_wxid` (`to_wxid`),
  KEY `idx_chatroom_id` (`chatroom_id`),
  KEY `idx_msg_type` (`msg_type`),
  KEY `idx_direction` (`direction`),
  KEY `idx_created_at` (`created_at`),
  CONSTRAINT `fk_message_robot` FOREIGN KEY (`robot_id`) REFERENCES `wechat_robot_accounts` (`id`) ON DELETE CASCADE,
  CONSTRAINT `fk_message_user` FOREIGN KEY (`user_id`) REFERENCES `users` (`id`) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='微信消息记录表';

-- 微信朋友圈表

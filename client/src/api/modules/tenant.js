import api from '@/api'

export const tenantApi = {
  getDashboard: () => api.get('/tenant/dashboard'),
  getProfile: () => api.get('/tenant/profile'),
  updateProfile: (data) => api.put('/tenant/profile', data),
  getDemands: () => api.get('/tenant/demands'),
  createDemand: (data) => api.post('/tenant/demands', data),
  updateDemand: (id, data) => api.put(`/tenant/demands/${id}`, data),
  deleteDemand: (id) => api.delete(`/tenant/demands/${id}`),
  getFavorites: () => api.get('/tenant/favorites'),
  addFavorite: (propertyId) => api.post('/tenant/favorites', { property_id: propertyId }),
  removeFavorite: (propertyId) => api.delete(`/tenant/favorites/${propertyId}`),
  getConversations: () => api.get('/tenant/conversations'),
  createConversation: (data) => api.post('/tenant/conversations', data),
  getMessages: (id) => api.get(`/tenant/conversations/${id}/messages`),
  sendMessage: (id, content) => api.post(`/tenant/conversations/${id}/messages`, { content }),
  getAppointments: () => api.get('/tenant/appointments'),
  createAppointment: (data) => api.post('/tenant/appointments', data),
  getApplications: () => api.get('/tenant/applications'),
  getContracts: () => api.get('/tenant/contracts'),
  getBills: () => api.get('/tenant/bills'),
  getDocuments: () => api.get('/tenant/documents'),
  getServiceTickets: () => api.get('/tenant/service-tickets'),
}
